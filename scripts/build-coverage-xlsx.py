wb = Workbook()

def build_sheet(ws, title, headers, rows, widths=None, total_row_vals=None, note_lines=None, freeze='C5'):
    last_col = len(headers) + 1
    setup_sheet(ws, title=title, last_col=last_col)
    for col_idx, h in enumerate(headers, start=2):
        ws.cell(row=4, column=col_idx, value=h)
    style_header_row(ws, row_num=4, col_start=2, col_end=last_col)
    for i, row_data in enumerate(rows):
        row_num = 5 + i
        for col_idx, value in enumerate(row_data, start=2):
            ws.cell(row=row_num, column=col_idx, value=value)
        style_data_row(ws, row_num=row_num, col_start=2, col_end=last_col, row_index=i)
    r_after = 5 + len(rows)
    if total_row_vals is not None:
        for col_idx, value in enumerate(total_row_vals, start=2):
            ws.cell(row=r_after, column=col_idx, value=value)
        style_total_row(ws, row_num=r_after, col_start=2, col_end=last_col)
        r_after += 1
    if note_lines:
        nr = r_after + 1
        for j, line in enumerate(note_lines):
            c = ws.cell(row=nr + j, column=2, value=line)
            c.font = font_caption()
            c.alignment = Alignment(horizontal='left', vertical='center')
    auto_fit_columns(ws, min_width=8, max_width=40, header_row=4, data_start_row=5)
    auto_fit_row_heights(ws, header_row=4, data_start_row=5)
    if widths:
        for col_letter, w in widths.items():
            ws.column_dimensions[col_letter].width = w
    ws.freeze_panes = freeze
    return ws

